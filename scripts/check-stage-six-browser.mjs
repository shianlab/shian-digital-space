import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const require = createRequire(path.join(process.env.SHIAN_BROWSER_RUNTIME, 'package.json'));
const browser = await require('playwright').chromium.launch({ channel: 'msedge', headless: true });
const output = 'docs/planning/materials/stage-06';
const report = { pageErrors: [], consoleErrors: [], failedRequests: [], checks: [], screenshots: [] };
const url = 'http://127.0.0.1:5175/dev/stage-six.html';
const snapshot = async (page, name) => { await page.screenshot({ path: `${output}/${name}.png`, fullPage: true }); report.screenshots.push(name); };
const metrics = page => page.evaluate(() => window.__stageSix);
const waitHome = page => page.waitForFunction(() => Math.abs(window.__stageSix?.cameraZ - 11.65) < .02 && Math.abs(window.__stageSix?.dodgeX) < .02);
const layoutCheck = async page => {
    await page.waitForFunction(() => window.__stageSix?.nameBounds && window.__stageSix?.labelBounds);
    const m = await metrics(page);
    assert.ok(m.foot.y < m.viewport.height - 10 && m.foot.y > m.head.y);
    assert.ok(m.labelBounds.bottomRight.y < m.head.y - 12, 'Labels must clear the crown');
    assert.ok(m.nameBounds.bottomRight.y < m.labelBounds.topLeft.y, 'Name must clear labels');
    assert.ok(m.labelBounds.topLeft.x >= 0 && m.labelBounds.bottomRight.x <= m.viewport.width);
    return m;
};
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', e => report.pageErrors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') report.consoleErrors.push(m.text()); });
    page.on('requestfailed', r => report.failedRequests.push(r.url()));
    const start = Date.now();
    await page.goto(url);
    await page.waitForFunction(() => window.__stageSix?.labelBounds);
    report.firstReadyMs = Date.now() - start;
    report.desktop = await layoutCheck(page);
    for (const speed of ['12', '20']) {
        await page.getByLabel('动作速度').selectOption(speed);
        const seen = new Set();
        for (let i = 0; i < 45 && seen.size < 9; i++) { seen.add((await metrics(page)).frame); await page.waitForTimeout(180); }
        assert.equal(seen.size, 9, `All nine frames must render at ${speed}fps`);
        report.checks.push(`${speed} FPS playback rendered all nine textures`);
    }
    await page.getByRole('button', { name: '暂停挥手', exact: true }).click();
    await page.getByLabel('静止帧', {exact:true}).focus();
    await page.getByLabel('静止帧', {exact:true}).press('End');
    await page.waitForFunction(() => window.__stageSix.frame === 9);
    await page.waitForTimeout(700);
    assert.equal((await metrics(page)).frame, 9);
    await page.getByRole('button', {name:'下一帧',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.frame === 1);
    await page.getByRole('button', {name:'上一帧',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.frame === 9);
    report.checks.push('Pause, keyboard frame slider, previous/next wrapping work');
    await snapshot(page,'desktop-final');
    await page.getByLabel('显示脚底参考线').check();
    await page.waitForTimeout(350);
    await snapshot(page,'feet-guide');
    await page.getByLabel('显示脚底参考线').uncheck();
    await page.getByRole('button',{name:'左侧看',exact:true}).click();
    await page.waitForTimeout(1000);
    await snapshot(page,'left-view');
    await page.getByRole('button',{name:'右侧看',exact:true}).click();
    await page.waitForTimeout(1000);
    await snapshot(page,'right-view');
    await page.getByRole('button',{name:'回到迎宾位置',exact:true}).click();
    for (let i=0;i<5;i++) await page.getByRole('button',{name:'向前走',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.cameraZ < 8.43 && window.__stageSix.dodgeX < -1.3);
    report.approach = await metrics(page);
    await snapshot(page,'approach-dodge');
    for (let i=0;i<5;i++) await page.getByRole('button',{name:'向前走',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.cameraZ < 5.23 && Math.abs(window.__stageSix.dodgeX) < .02);
    assert.ok(await page.getByRole('button',{name:'向前走',exact:true}).isDisabled());
    report.passed = await metrics(page);
    await snapshot(page,'passed-avatar');
    await page.getByRole('button',{name:'回到迎宾位置',exact:true}).click(); await waitHome(page);
    report.checks.push('Approach moves character left, passing clears the view, returning restores the grounded position');
    await page.getByRole('button',{name:'原人物对照',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.frame === null);
    await snapshot(page,'original-comparison');
    await page.getByRole('button',{name:'时安人物',exact:true}).click();
    await page.waitForFunction(() => window.__stageSix.frame === 9);
    await layoutCheck(page);
    report.checks.push('Original character / ShiAn comparison restores both variants');
    await page.getByRole('region',{name:'三维走廊小样，方向键前进后退'}).press('ArrowUp');
    await page.waitForFunction(() => window.__stageSix.cameraZ < 11.25);
    await page.getByRole('button',{name:'回到迎宾位置',exact:true}).click(); await waitHome(page);
    await page.setViewportSize({width:390,height:844}); await page.waitForTimeout(800);
    report.mobile390 = await layoutCheck(page);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await snapshot(page,'mobile-final');
    await page.setViewportSize({width:320,height:740}); await page.waitForTimeout(600);
    report.mobile320 = await layoutCheck(page);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    report.checks.push('390px and 320px fit the name, three labels and feet; no horizontal overflow; arrow navigation works');
    const requests = await page.evaluate(() => performance.getEntriesByType('resource').filter(e => e.name.includes('/textures/shian/corridor/')).map(e => ({url:e.name,bytes:e.encodedBodySize,durationMs:Math.round(e.duration)})));
    assert.equal(new Set(requests.map(r => r.url)).size, 9);
    report.characterLoads = requests;
    const reduced = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
    await reduced.goto(url); await reduced.waitForFunction(() => window.__stageSix?.frame === 5);
    assert.ok(await reduced.getByRole('button',{name:'播放挥手',exact:true}).isVisible());
    await reduced.waitForTimeout(600); assert.equal((await metrics(reduced)).frame,5);
    report.checks.push('Reduced-motion preference starts the character still');
    await reduced.close();
    assert.deepEqual(report.pageErrors,[]); assert.deepEqual(report.consoleErrors,[]); assert.deepEqual(report.failedRequests,[]);
    const failure = await browser.newPage();
    await failure.route('**/textures/shian/corridor/01.webp', route => route.fulfill({status:404,body:'missing test texture'}));
    await failure.goto(url);
    await failure.getByRole('alert').waitFor();
    assert.ok(await failure.getByRole('link',{name:'重新加载小样'}).isVisible());
    report.checks.push('A missing texture shows an explicit error and reload action (intentional 404 isolated from success checks)');
    await failure.close();
    report.status='passed';
} catch(error) { report.status='failed'; report.failure=error.stack; throw error; }
finally { fs.writeFileSync(`${output}/browser-inspection.json`,JSON.stringify(report,null,2)); await browser.close(); console.log(JSON.stringify({status:report.status,checks:report.checks,firstReadyMs:report.firstReadyMs,failure:report.failure})); }
